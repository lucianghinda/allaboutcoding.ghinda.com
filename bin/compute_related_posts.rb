#!/usr/bin/env ruby
# frozen_string_literal: true

# Precompute related posts and write _data/related_posts.yml, which is committed.
# The post layout reads that file; the deploy build computes nothing.
#
# Run it after publishing an article, then commit the result:
#
#   bundle exec ruby bin/compute_related_posts.rb
#
# How the ranking works, and why it is not just `jekyll build --lsi`:
#
# 1. Latent semantic indexing over post bodies, with code stripped out. Code
#    blocks are a large share of this blog and they pull unrelated posts
#    together on shared syntax rather than shared meaning.
#
# 2. Cosine similarity, not Jekyll's. Jekyll ranks with a raw dot product of
#    unnormalised vectors, so the longest post scores high against everything:
#    one article came out as the top suggestion for 88 of 110 posts. The gem
#    exposes a normalised variant, which is what this uses.
#
# 3. A bonus for tags shared with the post, weighted by how rare each tag is.
#    Sharing "claude-code" means something; sharing "ruby", which 92 of 110
#    posts carry, means almost nothing. LSI alone is strong on lexically
#    distinct topics and weak on the AI posts, whose vocabulary overlaps
#    loosely; the tag bonus covers that gap without overriding the text.
#
# Speed: classifier-reborn picks its SVD backend at require time. On the
# pure-Ruby backend this takes ~16 minutes; with numo and OpenBLAS it takes
# two seconds. See the :lsi group in the Gemfile for the setup.
#
# Future-dated posts are excluded on purpose: the production build drops them,
# so linking to one would be a 404 until its date arrives.

require "jekyll"
require "classifier-reborn"
require "yaml"

SOURCE   = File.expand_path("..", __dir__)
OUTPUT   = File.join(SOURCE, "_data", "related_posts.yml")
KEEP     = 5    # stored per post; the template renders fewer
CUTOFF   = 0.25 # share of singular values kept: lower generalises more
TAG_BOOST = 0.3 # weight of the tag bonus against the LSI cosine

# LSI should see prose, not fenced code, liquid tags, markup or bare URLs.
def prose_only(text)
  text
    .gsub(/^```.*?^```/m, " ")
    .gsub(/`[^`]*`/, " ")
    .gsub(/\{%.*?%\}/m, " ")
    .gsub(/<[^>]+>/, " ")
    .gsub(%r{https?://\S+}, " ")
    .gsub(/[^\p{L}\s]/, " ")
end

def tag_weights(posts)
  document_frequency = Hash.new(0)
  posts.each { |post| Array(post.data["tags"]).uniq.each { |tag| document_frequency[tag] += 1 } }
  total = posts.size.to_f
  document_frequency.transform_values { |count| Math.log(total / count) }
end

config = Jekyll.configuration(
  "source"      => SOURCE,
  "destination" => File.join(SOURCE, "_site"),
  "future"      => false,
  "quiet"       => true
)

site = Jekyll::Site.new(config)
site.reset
site.read

posts = site.posts.docs
abort "Found #{posts.size} posts, need at least 2." if posts.size < 2

warn "Indexing #{posts.size} posts (SVD backend: #{$SVD})..."
started = Process.clock_gettime(Process::CLOCK_MONOTONIC)

lsi = ClassifierReborn::LSI.new(auto_rebuild: false)
posts.each do |post|
  text = prose_only(post.content)
  lsi.add_item(post) { text }
end
lsi.build_index(CUTOFF)

weights = tag_weights(posts)
tags_of = posts.to_h { |post| [post.url, Array(post.data["tags"]).uniq] }

related = posts.to_h do |post|
  own_tags   = tags_of[post.url]
  own_weight = own_tags.sum { |tag| weights[tag] }

  scored = lsi.proximity_norms_for_content(post)
              .reject { |doc, _| doc.equal?(post) }
              .map do |doc, cosine|
    shared = own_weight.zero? ? 0 : (own_tags & tags_of[doc.url]).sum { |tag| weights[tag] } / own_weight
    [doc.url, cosine.to_f + (TAG_BOOST * shared)]
  end

  [post.url, scored.sort_by { |_, score| -score }.map(&:first).first(KEEP)]
end

elapsed = (Process.clock_gettime(Process::CLOCK_MONOTONIC) - started).round(1)

File.write(OUTPUT, <<~HEADER + YAML.dump(related))
  # Generated by bin/compute_related_posts.rb -- do not edit by hand.
  # Post URL => related post URLs, best first. Regenerate after publishing.
HEADER

# One post suggested everywhere is the failure mode worth watching, so report it.
top_slots = Hash.new(0)
related.each_value { |urls| urls.first(2).each { |url| top_slots[url] += 1 } }
hub, hits = top_slots.max_by { |_, count| count }

warn "Wrote #{OUTPUT} for #{related.size} posts in #{elapsed}s."
warn "  #{top_slots.size} distinct posts fill the two visible slots."
warn "  Most suggested: #{hub} (#{hits} posts)."
